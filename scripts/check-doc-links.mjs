#!/usr/bin/env node
// check-doc-links.mjs — verifies every relative link and image `src`/
// `srcset` in README.md, docs/USER_GUIDE.md, docs/TROUBLESHOOTING.md, and
// CHANGELOG.md points at a file that exists, OR is one of the
// not-yet-generated docs/screenshots/<name>-<theme>.png paths (T019).
// Node stdlib only. Not wired into `make check` — ad hoc verification for
// the T019 doc pass.

import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const PENDING_SCREENSHOT_NAMES = [
  'split', 'list', 'grid', 'zoom', 'usage', 'palette', 'quick-reply',
  'onboarding', 'projects', 'empty-not-running', 'compact', 'stats',
  'timeline', 'settings',
];
const PENDING_SCREENSHOTS = new Set();
for (const name of PENDING_SCREENSHOT_NAMES) {
  for (const theme of ['dark', 'light']) {
    PENDING_SCREENSHOTS.add(`docs/screenshots/${name}-${theme}.png`);
  }
}

const DOCS = ['README.md', 'docs/USER_GUIDE.md', 'docs/TROUBLESHOOTING.md', 'CHANGELOG.md'];

// Markdown link/image targets: [text](target) and src="target"/srcset="target".
const LINK_RE = /\]\(([^)]+)\)/g;
const ATTR_RE = /(?:src|srcset)="([^"]+)"/g;

function isExternal(target) {
  return /^([a-z][a-z0-9+.-]*:)/i.test(target) || target.startsWith('#');
}

function checkFile(relDoc) {
  const abs = path.join(ROOT, relDoc);
  const text = readFileSync(abs, 'utf8');
  const docDir = path.dirname(abs);
  const targets = [];
  for (const m of text.matchAll(LINK_RE)) targets.push(m[1]);
  for (const m of text.matchAll(ATTR_RE)) targets.push(m[1]);

  const missing = [];
  const pending = [];
  const ok = [];
  for (let raw of targets) {
    raw = raw.split('#')[0].trim();
    if (!raw || isExternal(raw)) continue;
    const relFromRoot = path.relative(ROOT, path.join(docDir, raw)).split(path.sep).join('/');
    if (existsSync(path.join(docDir, raw))) {
      ok.push(relFromRoot);
    } else if (PENDING_SCREENSHOTS.has(relFromRoot)) {
      pending.push(relFromRoot);
    } else {
      missing.push(relFromRoot);
    }
  }
  return { ok, pending: [...new Set(pending)], missing: [...new Set(missing)] };
}

let anyMissing = false;
const allPending = new Set();
for (const doc of DOCS) {
  const { ok, pending, missing } = checkFile(doc);
  console.log(`\n${doc}: ${ok.length} link(s)/image(s) resolved, ${pending.length} pending screenshot(s), ${missing.length} missing`);
  for (const p of pending) allPending.add(p);
  if (missing.length) {
    anyMissing = true;
    for (const m of missing) console.log(`  MISSING: ${m}`);
  }
}

console.log(`\nPending screenshots referenced (not yet generated by \`make screenshots\`):`);
for (const p of [...allPending].sort()) console.log(`  ${p}`);

if (anyMissing) {
  console.error('\ncheck-doc-links: FAILED — some links/images point at files that do not exist and are not pending screenshots');
  process.exit(1);
}
console.log('\ncheck-doc-links: OK — every link/image resolves or is a pending screenshot');
